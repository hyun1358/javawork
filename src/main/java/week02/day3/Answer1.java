/*
 * [정답 + 해설 1] Week 02 Day 3
 * 문제: 1부터 10까지 출력
 */
public class Answer1 {
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i++) {
            System.out.print(i + " ");
        }
    }
}
