package week11.day3;

/**
 * [연습 문제 5] 패턴 선택 기준
 * 문제: 어떤 경우에 빌더를 쓰고, 어떤 경우에 팩토리를 쓰는지 차이를 주석으로 설명하세요.
 */
public class Problem5 {
    public static void main(String[] args) {
        /*
         * [빌더 패턴(Builder Pattern) vs 팩토리 패턴(Factory Pattern) 핵심 비교]
         * 
         * 1. 빌더 패턴 (Builder Pattern)
         *    - 사용 목적: "복잡한 단일 객체의 단계별 조립"
         *    - 주 사용 케이스:
         *      - 객체의 멤버 변수가 너무 많아 생성자가 비대해질 때 (Telescoping Constructor 방지).
         *      - 일부 필드는 선택적으로 설정하고 싶을 때 (null 값 전달 방지).
         *      - 동일한 조립 과정에서 서로 다른 속성을 가진 다양한 객체를 유연하게 만들어야 할 때.
         *    - 특징: 체이닝 방식(.name().age().build())을 사용해 코드 가독성을 극대화합니다.
         * 
         * 2. 팩토리 패턴 (Factory Pattern - 팩토리 메서드 / 추상 팩토리)
         *    - 사용 목적: "구체 클래스 의존성을 감추고 객체 생성 작업을 캡슐화"
         *    - 주 사용 케이스:
         *      - 클라이언트가 어떤 구체적인 클래스(자식 클래스)를 만들어야 할지 모르는 경우.
         *      - 객체 생성의 구체적인 로직(조건 분기 등)을 팩토리 클래스 한 곳에 모아 관리하고 싶을 때.
         *      - 생성되는 여러 제품군(Product)을 결합하여 다형성(Polymorphism)을 활용해야 할 때.
         *    - 특징: 클라이언트는 인터페이스나 부모 타입에만 의존하며, new 키워드를 직접 호출하지 않습니다.
         * 
         * 3. 한 줄 요약
         *    - 빌더는 "하나의 복잡한 객체를 어떻게 만들(조립할) 것인가"에 집중하고,
         *    - 팩토리는 "여러 종류의 객체 중 어떤 것을 생성해서 제공할 것인가"에 집중합니다.
         */
    }
}
