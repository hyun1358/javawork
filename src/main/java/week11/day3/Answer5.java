public class Answer5 {
    // 메인 메서드
    public static void main(String[] args) {
        /*
         * [빌더 패턴 vs 팩토리 패턴의 핵심 차이점]
         * 
         * 빌더 패턴(Builder Pattern): 
         *   - 객체의 생성자의 매개변수가 너무 많거나, 생성 시 객체의 속성을 부분적으로 조립해서 유연하게 만들어야 할 때 주로 사용합니다.
         * 
         * 팩토리 패턴(Factory Pattern): 
         *   - 객체를 생성할 때 생성 로직을 노출하지 않고, 인터페이스(또는 상위 클래스) 타입으로 반환합니다.
         *   - 실제 생성되는 구체적인 하위 클래스가 무엇인지를 조건이나 상황에 따라 팩토리 클래스 내부에서 결정하여 반환할 때 주로 사용합니다.
         */
    }
}
